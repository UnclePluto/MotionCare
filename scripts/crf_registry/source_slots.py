def build_source_slots(document_path: Path) -> dict:
    """对照源文件生成清单；cell_index 按每行直接 w:tc 子节点计数。

    不使用 gridSpan 展开后的网格：python-docx 消费者取 row._tr.tc_lst[index]，
    需要 Cell 包装时使用 _Cell(tc, table)，不能用 row.cells[index]。
    """
    digest = hashlib.sha256(document_path.read_bytes()).hexdigest()
    if digest != SOURCE_SHA256:
        raise ValueError("CRF 原表哈希不符，须重新审核填写位清单")
    with ZipFile(document_path) as archive:
        document = ET.fromstring(archive.read("word/document.xml"))
    tables = []
    for table in document.findall("w:body/w:tbl", NS):
        rows = []
        for row in table.findall("w:tr", NS):
            rows.append(
                [
                    "\n".join("".join(p.itertext()) for p in cell.findall("w:p", NS))
                    for cell in row.findall("w:tc", NS)
                ]
            )
        tables.append(rows)
    result = []
    for table_index, row_index, definitions in SOURCE_ROWS:
        counters = {}
        for slot_index, (label, cell_indices, options) in enumerate(definitions):
            cell_index = cell_indices[0]
            slot_order = counters.get(cell_index, 0)
            counters[cell_index] = slot_order + 1
            visit_type = (
                "T0"
                if table_index in (3, 4, 5, 6, 7, 13, 14)
                else "T1"
                if 15 <= table_index <= 21
                else "T2"
                if 22 <= table_index <= 28
                else None
            )
            result.append(
                {
                    "slot_id": f"T{table_index:02d}.R{row_index:02d}.S{slot_index:02d}",
                    "label": label,
                    "index_space": "xml_tc",
                    "table_index": table_index,
                    "row_index": row_index,
                    "cell_index": cell_index,
                    "cell_indices": cell_indices,
                    "slot_order": slot_order,
                    "options": options,
                    "visit_type": visit_type,
                    "source_cells": [
                        tables[table_index][row_index][i] for i in cell_indices
                    ],
                }
            )
    return {
        "source_sha256": digest,
        "index_base": 0,
        "index_space": "xml_tc",
        "table_count": len(tables),
        "row_count": sum(map(len, tables)),
        "tables": [
            {
                "table_index": i,
                "row_count": len(rows),
                "cell_counts": [len(r) for r in rows],
            }
            for i, rows in enumerate(tables)
        ],
        "slots": result,
    }
